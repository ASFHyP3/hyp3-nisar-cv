from osgeo import gdal, osr
from nisar_cv.gcov import acquisition_date, acquisition_frame
from pathlib import Path
from nisar_cv.aws import get_content_type
import json

def build_nisar_cv_asset(asset_fp: Path) -> dict:
    """
    Build assets with more accurate descriptions based on NISAR-Cv scheme
    """
    if asset_fp.stem.endswith("CV"):  # full resolution coefficient of variation product
        asset_roles = ["data", "visual"]
        description = "Full resolution Coefficient of Variation (CV) product."
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_fp.stem.endswith("CV_100m"):
        asset_roles = ["data", "overview"]
        description = "100m resolution Coefficient of Variation (CV) product."
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_fp.stem.endswith("CROP_100m"):
        asset_roles = ["data", "overview"]
        description = "100m resolution crop area classification map."
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_fp.stem.endswith("NVALID"):
        asset_roles = ["data", "data-mask"]
        description = "Mask of valid pixels in source GOV granules. 1-5 = valid, 0 = partially focused or invalid, 255 = outside acquisition"
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_fp.stem.endswith("WATER"):
        asset_roles = ["data", "water-mask"]
        description = "Watermask for subset area, generated by determining whether each pixel is above the water backscatter threshold in a significant fraction of the images"
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    else:
        asset_roles = ["data"]
        description = ""
        asset_type = ""
    return build_asset(
        asset_fp,
        asset_roles=asset_roles,
        description=description,
        asset_type=asset_type)


def build_asset(
        asset_fp: Path,
        parent: Path = Path("."),
        asset_roles: list[str] | tuple[str] = ("data",),
        description: str = "",
        asset_type: str = ""
) -> dict:
    asset_roles = list(asset_roles)
    if not asset_type:
        asset_type = get_content_type(asset_fp)
    asset = {
        "href": str(parent / asset_fp.name),
        "roles": asset_roles,
        "type": asset_type,
        "title": str(Path(asset_fp.stem)),
    }
    if description:
        asset["description"] = description
    return asset


def write_stac_file(
        stac_file: Path,
        stac_id: str,
        bounding_box: list[float],
        assets: dict,
        properties: dict,
        collection: str,
        stac_url: str | Path
) -> Path:
    assert 'datetime' in properties.keys(), "Field 'datetime' required in properties"
    stac_dict = {
        "type": "Feature",
        "stac_version": "1.1.0",
        "id": stac_id,
        "geometry": {
            "type": "Polygon",
            "coordinates": [
                [
                    [bounding_box[0], bounding_box[1]],
                    [bounding_box[2], bounding_box[1]],
                    [bounding_box[2], bounding_box[3]],
                    [bounding_box[0], bounding_box[3]],
                    [bounding_box[0], bounding_box[1]],
                ]
            ],
        },
        "bbox": bounding_box,
        "properties": properties,
        "collection": collection,
        "links": [
            {
                "rel": "self",
                "href": str(stac_url),
                "title": f"{stac_id} STAC Item",
                "type": "application/geo+json",
            }
        ],
        "assets": assets,
    }
    with open(Path("./output") / stac_file, "w") as f:
        json.dump(stac_dict, f)
    return stac_file


def get_bounding_box_union(geotiff_fps) -> list[float]:
    bounding_box = []
    for geotiff_fp in geotiff_fps:
        dataset = gdal.Open(str(geotiff_fp))
        srs = osr.SpatialReference()
        srs.ImportFromEPSG(4326)
        dataset_bounds = list(dataset.GetExtent(srs=srs))
        if not bounding_box:
            bounding_box = dataset_bounds
        else:
            bounding_box[0] = min(bounding_box[0], dataset_bounds[0])
            bounding_box[1] = min(bounding_box[1], dataset_bounds[1])
            bounding_box[2] = max(bounding_box[2], dataset_bounds[2])
            bounding_box[3] = max(bounding_box[3], dataset_bounds[3])
    return bounding_box


def create_nisar_cv_stac_item(
        granules: list[str],
        product_fps: list[Path],
        bucket: str,
        prefix: str = ""
) -> Path:
    """
    Create a JSON STAC item from the output files which are going in the s3 bucket.
    """
    stac_id = f"nisar-cv-{prefix}"
    stac_file = f"{stac_id}.stac.json"
    stac_fp = Path('./output') / stac_file
    key = str(Path(prefix) / stac_file)
    stac_url = f"s3://{bucket}/{key}"

    bounding_box: list = []
    start_datetime = None
    end_datetime = None
    file_list = []
    assets = {}
    granule_frames = set()
    # find bounding box which includes all files
    for product_fp in product_fps:
        file_list.append(product_fp.name)
        assets[product_fp.stem] = build_nisar_cv_asset(Path(product_fp))

    bounding_box = get_bounding_box_union(product_fps)
    # get date and time from granule names
    for granule in granules:
        granule_frame = acquisition_frame(granule)
        granule_frames.add(granule_frame)
        granule_date = acquisition_date(granule)
        if start_datetime is None:
            start_datetime = granule_date
        else:
            start_datetime = min(granule_date, start_datetime)
        if end_datetime is None:
            end_datetime = granule_date
        else:
            end_datetime = max(granule_date, end_datetime)
        print(
            f"start_datetime: {start_datetime.isoformat()}, end_datetime: {end_datetime.isoformat()}"
        )
    assert start_datetime is not None, "No dataset start date found!"
    assert end_datetime is not None, "No dataset end date found!"
    mid_datetime = start_datetime + (end_datetime - start_datetime) / 2
    properties = {
        "start_datetime": start_datetime.isoformat(),
        "end_datetime": end_datetime.isoformat(),
        "datetime": mid_datetime.isoformat(),
        "frames": list(granule_frames)
    }

    write_stac_file(
        stac_file=Path(stac_file),
        stac_id=stac_id,
        bounding_box=bounding_box,
        properties=properties,
        assets=assets,
        collection="nisar-bridge",
        stac_url=stac_url
    )

    return stac_fp
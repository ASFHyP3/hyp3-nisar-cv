from pathlib import Path

import pystac
from osgeo import gdal, osr

from nisar_cv.aws import get_content_type
from nisar_cv.gcov import acquisition_date, acquisition_frame


def build_nisar_cv_asset(
    asset_path: Path, bucket, prefix, parent: str = "."
) -> pystac.Asset:
    """
    Build assets with more accurate descriptions based on NISAR-Cv scheme
    """
    if asset_path.stem.endswith(
        "CV"
    ):  # full resolution coefficient of variation product
        asset_roles = ["data", "visual"]
        description = "Full resolution Coefficient of Variation (CV) product."
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_path.stem.endswith("CV_100m"):
        asset_roles = ["data", "overview"]
        description = "100m resolution Coefficient of Variation (CV) product."
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_path.stem.endswith("CROP_100m"):
        asset_roles = ["data", "overview"]
        description = "100m resolution crop area classification map."
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_path.stem.endswith("NVALID"):
        asset_roles = ["data", "data-mask"]
        description = (
            "Number of source GCOV granules in which a pixel is masked as valid"
        )
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    elif asset_path.stem.endswith("WATER"):
        asset_roles = ["data", "water-mask"]
        description = "Watermask for subset area, generated by determining whether each pixel is above the water backscatter threshold in a significant fraction of the images"
        asset_type = "image/tiff; application=geotiff; profile=cloud-optimized"
    else:
        asset_roles = ["data"]
        description = ""
        asset_type = get_content_type(asset_path)
    file_size = asset_path.stat().st_size
    asset = pystac.Asset(
        href=f"{parent}/{asset_path.name}",
        roles=asset_roles,
        description=description,
        media_type=asset_type,
        extra_fields={
            "alternate": {
                "s3": {
                    "href": f"s3://{bucket}/{prefix}/{asset_path.name}",
                    "alternate:name": "S3",
                }
            },
            "file:size": file_size,
        },
    )

    return asset


def get_bounding_box_union(geotiff_paths: list[Path]) -> list[float]:
    bounding_box: list[float] = []
    srs = osr.SpatialReference()
    srs.ImportFromEPSG(4326)
    for geotiff_path in geotiff_paths:
        dataset = gdal.Open(str(geotiff_path))
        gdal_dataset_bounds = list(dataset.GetExtent(srs=srs))
        # GDAL bounds [latmin, latmax, lonmin, lonmax], so we need to redefine it to [lonmin, latmin, lonmax, latmax]
        dataset_bounds = [
            gdal_dataset_bounds[2],
            gdal_dataset_bounds[0],
            gdal_dataset_bounds[3],
            gdal_dataset_bounds[1],
        ]
        if not bounding_box:
            bounding_box = dataset_bounds
        else:
            bounding_box[0] = min(bounding_box[0], dataset_bounds[0])
            bounding_box[1] = min(bounding_box[1], dataset_bounds[1])
            bounding_box[2] = max(bounding_box[2], dataset_bounds[2])
            bounding_box[3] = max(bounding_box[3], dataset_bounds[3])
    return bounding_box


def create_nisar_cv_stac_item(
    granules: list[str], product_paths: list[Path], bucket: str, prefix: str = ""
) -> Path:
    """
    Create a JSON STAC item from the output files which are going in the s3 bucket.
    """
    stac_id = f"nisar-cv-{prefix}"
    stac_file = f"{stac_id}.stac.json"
    stac_path = Path("./output") / stac_file
    key = str(Path(prefix) / stac_file)
    stac_url = f"s3://{bucket}/{key}"
    file_list = []
    assets = {}

    # find bounding box which includes all files
    for product_path in product_paths:
        file_list.append(product_path.name)
        assets[product_path.stem] = build_nisar_cv_asset(
            Path(product_path), bucket, prefix
        )

    bounding_box = get_bounding_box_union(product_paths)
    # get date and time from granule names
    granule_frames = {acquisition_frame(granule) for granule in granules}
    granule_dates = {acquisition_date(granule) for granule in granules}
    start_datetime = min(granule_dates)
    end_datetime = max(granule_dates)
    mid_datetime = start_datetime + (end_datetime - start_datetime) / 2
    properties = {
        "frames": list(granule_frames),
    }
    stac_item = pystac.Item(
        id=stac_id,
        stac_extensions=[
            "https://stac-extensions.github.io/file/v2.1.0/schema.json",
            "https://stac-extensions.github.io/alternate-assets/v1.2.0/schema.json",
        ],
        geometry={
            "type": "Polygon",
            "coordinates": [
                [
                    [bounding_box[0], bounding_box[1]],
                    [bounding_box[2], bounding_box[1]],
                    [bounding_box[2], bounding_box[3]],
                    [bounding_box[0], bounding_box[3]],
                    [bounding_box[0], bounding_box[1]],
                ]
            ],
        },
        bbox=bounding_box,
        properties=properties,
        # collection="nisar-cv", #not currently defined, will be defined in the future
        href=str(stac_url),
        assets=assets,
        datetime=mid_datetime,
        start_datetime=start_datetime,
        end_datetime=end_datetime,
    )
    stac_item.validate()
    pystac.write_file(stac_item, dest_href=stac_path)
    return stac_path
